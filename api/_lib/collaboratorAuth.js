/**
 * api/_lib/collaboratorAuth.js
 *
 * Shared server-side resolver for "what is this authenticated user allowed
 * to do, on whose wedding, as a collaborator." Originally tried to resolve
 * this straight off the Collaborator record via the admin key — confirmed
 * empirically that's impossible (a scoped read returns 200/[], a scoped
 * update returns a flat 403; the admin key has no session identity to
 * satisfy Collaborator's owner-scoped {{user.id}} RLS). Collaborator's own
 * RLS is untouched (approved design) — this resolver goes through
 * CollaboratorGrant instead, a small, purpose-built, append-only entity
 * (create:null/read:null, same shape as RsvpResponse/PollVote) written by
 * the collaborator's own bearer token at accept time (api/collaborator-accept.js),
 * never by the admin key. Ids are stored as HMAC digests (hashId) — an
 * unscoped list of this entity (anyone, any API token, since read:null)
 * yields opaque hash pairs, never a real user id, and forging a row that
 * targets a real owner/collaborator pair requires knowing COLLAB_HASH_KEY.
 *
 * This is real, server-enforced permission checking — not menu-hiding. A
 * request that skips the UI entirely and hits a collaborator-proxy endpoint
 * straight is checked exactly the same way.
 */

import crypto from 'crypto';
import { collaboratorCan } from '../../src/lib/collaboratorPageMap.js';
import { encKey } from './appKeys.js';

const BASE44_API = 'https://base44.app/api';
const BASE44_APP_ID = process.env.VITE_BASE44_APP_ID || '68731d183f075e406eda2236';
/**
 * The key every collaborator hash and invite signature is made with.
 *
 * COLLAB_HASH_KEY is 32 random bytes as hex, generated by the owner and set
 * in Vercel and in Base44 secrets, so the hosted collaborator function makes
 * the same hashes. Owner ruling 2026-10-12: BASE44_ADMIN_KEY is a bearer
 * credential and is never a hashing key. It was this key until then, so
 * grants made before the switch do not match, and were rebuilt once by
 * scripts/collab-grants-rebuild.ts.
 *
 * Read on every call, and refused when it is missing or not 64 hex
 * characters: a missing key must fail closed, never hash under an empty key
 * that anyone could reproduce.
 */
export function collabHashKey() {
  const key = process.env.COLLAB_HASH_KEY || '';
  if (!/^[0-9a-f]{64}$/i.test(key)) throw new Error('COLLAB_HASH_KEY is missing or is not 64 hex characters');
  return key;
}

/** One-way HMAC-SHA256 digest, keyed with COLLAB_HASH_KEY, never reversible without that secret. */
export function hashId(rawValue) {
  if (!rawValue) return null;
  return crypto.createHmac('sha256', collabHashKey()).update(String(rawValue)).digest('hex');
}

/**
 * THE OWNER'S ID, ENCRYPTED, on the grant written at accept (owner ruling
 * 2026-10-13). The hashes above cannot be reversed, so a collaborator who signs
 * in without the invite link had no way back to the wedding they help with.
 *
 * Encrypted under APP_ENC_KEY (api/_lib/appKeys.js), never COLLAB_HASH_KEY: one
 * key per job, hashing or encryption, never both. AES-256-GCM, with the row's
 * collaborator hash as additional data, so a value copied onto another
 * person's grant does not decrypt. Format: v1.<iv>.<tag>.<ciphertext>, each
 * base64url.
 */
export function encryptOwnerId(ownerUserId, collaboratorUserIdHash) {
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', encKey(), iv);
  cipher.setAAD(Buffer.from(String(collaboratorUserIdHash)));
  const ct = Buffer.concat([cipher.update(String(ownerUserId), 'utf8'), cipher.final()]);
  return ['v1', iv, cipher.getAuthTag(), ct].map((p, i) => (i === 0 ? p : p.toString('base64url'))).join('.');
}

/** The owner's id, or null for anything that does not decrypt under this row's collaborator hash. */
export function decryptOwnerId(value, collaboratorUserIdHash) {
  try {
    const [v, iv, tag, ct] = String(value || '').split('.');
    if (v !== 'v1' || !iv || !tag || !ct) return null;
    const decipher = crypto.createDecipheriv('aes-256-gcm', encKey(), Buffer.from(iv, 'base64url'));
    decipher.setAAD(Buffer.from(String(collaboratorUserIdHash)));
    decipher.setAuthTag(Buffer.from(tag, 'base64url'));
    return Buffer.concat([decipher.update(Buffer.from(ct, 'base64url')), decipher.final()]).toString('utf8');
  } catch {
    return null;
  }
}

function unwrapList(payload) {
  if (Array.isArray(payload)) return payload;
  if (Array.isArray(payload?.data)) return payload.data;
  if (Array.isArray(payload?.results)) return payload.results;
  return [];
}

async function adminFetch(method, path, adminKey, body) {
  const res = await fetch(`${BASE44_API}${path}`, {
    method,
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${adminKey}` },
    ...(body !== undefined ? { body: JSON.stringify(body) } : {}),
  });
  if (!res.ok) {
    const text = await res.text().catch(() => '');
    throw new Error(`Base44 ${method} ${path} failed (${res.status}): ${text.slice(0, 200)}`);
  }
  if (res.status === 204) return null;
  return res.json();
}

/**
 * This user's current access to ONE specific owner's wedding — the latest
 * CollaboratorGrant event for (ownerUserId, userId), or null if there is
 * none, or the most recent event was a revoke.
 *
 * @returns {Promise<{permissions: object}|null>}
 */
export async function getCollaborationFor(userId, ownerUserId, adminKey) {
  const ownerHash = hashId(ownerUserId);
  const collabHash = hashId(userId);
  const query = encodeURIComponent(JSON.stringify({ owner_user_id_hash: ownerHash, collaborator_user_id_hash: collabHash }));
  const rows = unwrapList(await adminFetch('GET', `/apps/${BASE44_APP_ID}/entities/CollaboratorGrant?q=${query}`, adminKey));
  // Defense in depth: re-check both hashes match exactly, don't just trust the query filter.
  const relevant = rows.filter(r => r.owner_user_id_hash === ownerHash && r.collaborator_user_id_hash === collabHash);

  const latest = latestEvent(relevant);

  if (!latest || latest.event_type !== 'grant') return null;
  return { permissions: latest.permissions || {} };
}

/**
 * The event that decides access, out of one owner and collaborator pair's
 * rows. Latest created_date wins; two events with the same created_date
 * resolve to the revoke, so a removal can never lose a tie to a grant.
 */
export function latestEvent(rows) {
  return rows.reduce((best, r) => {
    if (!best) return r;
    const a = new Date(r.created_date).getTime();
    const b = new Date(best.created_date).getTime();
    if (a > b) return r;
    if (a === b && r.event_type === 'revoke') return r;
    return best;
  }, null);
}

/**
 * The wedding a collaborator-only account goes to when it signs in without the
 * invite link (owner ruling 2026-10-13): of every owner whose latest event for
 * this collaborator is a grant, the one accepted most recently. A later item
 * may offer a picker; for now the most recent wins.
 *
 * The owner comes from owner_id_enc, and only counts when it hashes back to
 * the row's own owner hash, so a forged or copied value is ignored. Returns
 * { ownerUserId, permissions } or null.
 */
export async function mostRecentCollaboration(userId, adminKey) {
  const collabHash = hashId(userId);
  if (!collabHash) return null;
  const query = encodeURIComponent(JSON.stringify({ collaborator_user_id_hash: collabHash }));
  const rows = unwrapList(await adminFetch('GET', `/apps/${BASE44_APP_ID}/entities/CollaboratorGrant?q=${query}`, adminKey))
    .filter(r => r.collaborator_user_id_hash === collabHash && !r.is_test);

  const byOwner = new Map();
  for (const r of rows) {
    if (!byOwner.has(r.owner_user_id_hash)) byOwner.set(r.owner_user_id_hash, []);
    byOwner.get(r.owner_user_id_hash).push(r);
  }

  let best = null;
  for (const [ownerHash, events] of byOwner) {
    const latest = latestEvent(events);
    if (!latest || latest.event_type !== 'grant') continue;
    // The accept rows carry owner_id_enc; a permission edit's grant may not.
    const accepted = events
      .filter(r => r.event_type === 'grant' && r.owner_id_enc)
      .map(r => ({ r, ownerUserId: decryptOwnerId(r.owner_id_enc, collabHash) }))
      .filter(x => x.ownerUserId && hashId(x.ownerUserId) === ownerHash)
      .sort((a, b) => new Date(b.r.created_date) - new Date(a.r.created_date))[0];
    if (!accepted) continue;
    const at = new Date(accepted.r.created_date).getTime();
    if (!best || at > best.at) best = { at, ownerUserId: accepted.ownerUserId, permissions: latest.permissions || {} };
  }
  return best ? { ownerUserId: best.ownerUserId, permissions: best.permissions } : null;
}

/** Every CollaboratorGrant row under one owner, re-checked against the hash rather than trusting the query filter. */
export async function listGrantsForOwner(ownerUserId, adminKey) {
  const ownerHash = hashId(ownerUserId);
  if (!ownerHash) return [];
  const query = encodeURIComponent(JSON.stringify({ owner_user_id_hash: ownerHash }));
  const rows = unwrapList(await adminFetch('GET', `/apps/${BASE44_APP_ID}/entities/CollaboratorGrant?q=${query}`, adminKey));
  return rows.filter(r => r.owner_user_id_hash === ownerHash);
}

/**
 * True if `permissions` grants at least `level` ('view' or 'edit') on `page`.
 * Item 5 (owner ruling 2026-10-12): every page is view only, so edit is false
 * for every page until a write PR adds it to COLLABORATOR_EDIT_PAGES, and a
 * stale grant that says edit does nothing.
 */
export function hasPagePermission(permissions, page, level) {
  return collaboratorCan(permissions, page, level);
}
