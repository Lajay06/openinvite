/**
 * The wedding-day row does not shout.
 *
 * ── THE STRING ─────────────────────────────────────────────────────────────
 *
 * buildScheduleEvents emits one synthetic row for the wedding day itself, and
 * its description read "Your special day!" — the one exclamation mark left in
 * product chrome, and on a row with unusually wide reach: it appears in the
 * Schedule list, in the calendar, and now in the exported workbook. Three
 * surfaces, one shout.
 *
 * Owner copy, round two: "The part everyone came for."
 *
 * ── WHY THIS IS PINNED AND NOT JUST SWEPT ──────────────────────────────────
 *
 * The exclamation rule is about product CHROME, and this row is chrome by
 * every reading — it is generated by us, not written by the couple, and no
 * guest sees it as part of a designed guest site. Nothing enforced that here,
 * which is how it survived the calm pass: the row is built in a lib, not
 * written as a string in a page, so a sweep looking at JSX never saw it.
 */
import { readFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { pass, fail } from './_shared.mjs';
import { buildScheduleEvents } from '../../src/lib/scheduleEvents.js';

const __dir = dirname(fileURLToPath(import.meta.url));
const SRC = readFileSync(resolve(__dir, '../../src/lib/scheduleEvents.js'), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

export async function runWeddingDayRowCopy() {
  const results = [];
  const check = (n, ok, d) => results.push(ok ? pass(n, d) : fail(n, 'see name', d));
  console.log('\n  The wedding-day row — chrome, so it does not shout:\n');

  const rows = buildScheduleEvents({
    invitation: { wedding_date: '2027-07-03', couple_names: 'Ada & Alan' },
    weddingDate: '2027-07-03',
  });
  const day = rows.find((r) => r.id === 'wedding-day');

  check('the wedding day is still a row', !!day, day ? day.title : 'missing');
  check('  it reads the owner’s line', day?.description === 'The part everyone came for.', day?.description);
  check('  and the exclamation is gone', !/Your special day/.test(SRC) && !day?.description.includes('!'), 'no shout');

  // The whole lib, not only this row: it is the one place chrome strings for
  // the schedule are generated, so it is worth holding all of them.
  const shouts = [...SRC.matchAll(/'([^']*!)'/g)].map((m) => m[1]);
  check('no string generated by this lib carries an exclamation mark',
    shouts.length === 0, shouts.join(' | ') || 'none');

  check('the title is untouched — only the description was the problem',
    day?.title === 'Wedding day: Ada & Alan', day?.title);

  return results;
}
